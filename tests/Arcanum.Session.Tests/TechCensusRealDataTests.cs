    /// <summary>Records carried by an item prototype, per state, over the audit's 65 (the rest are named by no item, or by items the data lists under no spell slot): filled with <see cref="Expected"/>.</summary>
    private const string CarriedTally = "65 carried: RUNS 45 HERO 0 PART 11 INERT 9";

    [TestMethod, TestCategory("RealData")]
    public void Every_technology_record_has_the_listed_state()
    {
        var root = Environment.GetEnvironmentVariable("DAT_ROOT");
        if (string.IsNullOrWhiteSpace(root)) Assert.Inconclusive("DAT_ROOT is required for the opt-in technology census; this is not a synthetic pass.");
        using var stack = ContentStack.Open(ContentMountPlan.Discover(root).Plan!).Stack!;
        var spells = SpellData.Open(stack, SpellRecordMode.LikeOriginal);
        Assert.AreEqual(SpellDataStatus.Read, spells.Status, $"{spells.Refusal}");
        var source = ContentPhase.Candidate(stack, AreaEffectsPath, ContentLoadPhase.GameStart) ?? throw new AssertFailedException($"{AreaEffectsPath} missing");
        var read = stack.Read(source);
        Assert.AreEqual(ContentReadStatus.Read, read.Status);
        var effects = MesFile.Parse(read.Bytes!, new()).File ?? throw new AssertFailedException($"{AreaEffectsPath} not parsed");
        // The viewer's rule of a number (as in the magic census): a rule the session refuses is none. The technology records name effects of effect.mes (50 and up) and some it lacks (none).
        SessionEffectDefinition? Effect(int number)
        {
            try { return EffectRules.Read(effects, number).Rule is { } rule ? SessionEffectDefinition.FromRule(rule) : null; }
            catch (ArgumentException) { return null; }
        }

        var prototypes = ContentPrototypes.Open(stack);
        // The viewer's reader of a summoned prototype (TerrainViewerSummon.SummonPrototypeOf).
        int? PrototypeType(int file) => ObjectSoundReader.ReadPrototype(prototypes.Read, file).Fields is { } fields ? fields.Type : null;

        // The records the installed item prototypes carry in a spell slot (the audit's 65 of 83).
        var carried = new HashSet<int>();
        foreach (var number in prototypes.Numbers)
            if (CombatFieldReader.ReadPrototype(prototypes.Read, number).Fields is { Item: { } item })
                foreach (var slot in item.Spells)
                    if (slot != 10000 && (slot & 0xFF) is var spell && spell >= SpellRecord.FirstTechnology && spell < SpellRecord.Count) carried.Add(spell);

        var expected = Expected.ToDictionary(e => e.Record, e => (e.State, e.Hero, e.Npc));
        Assert.AreEqual(Expected.Length, expected.Count, "one row per record");
        Assert.IsTrue(expected.Keys.All(k => k is >= SpellRecord.FirstTechnology and < SpellRecord.Count), "rows name technology records only");
        var differences = new List<string>();
        var states = new Dictionary<int, string>();
        for (var number = SpellRecord.FirstTechnology; number < SpellRecord.Count; number++)
        {
            var record = SessionSpellRecords.Translate(spells.Data!.Records[number]);
            var actual = Classify(record, Effect, PrototypeType);
            states[number] = actual.State;
            if (actual != expected.GetValueOrDefault(number, ("RUNS", "", ""))) differences.Add($"        ({number}, \"{actual.State}\", \"{actual.Hero}\", \"{actual.Npc}\"),");
        }
        var tally = Tally(states.Where(s => carried.Contains(s.Key)));
        Console.WriteLine($"technology records {states.Count}, carried by an item {carried.Count}; carried per state: {tally}; all per state: {Tally(states)}");
        Assert.AreEqual(0, differences.Count, "the census changed; the rows as they are now (a row of RUNS with two empty lists is removed):\n" + string.Join("\n", differences));
        Assert.AreEqual(CarriedTally, $"{carried.Count} carried: {tally}", "the records carried by an item, by state");
    }

    /// <summary>The state rules on synthetic records (root checks): each of the four words, and the NPC-only gap that makes a HERO row.</summary>
    [TestMethod]
    public void The_state_words_follow_the_components_the_host_takes()
    {
        var area = new SpellArea(0x40, 0, 0, 0, -1);
        static SpellComponent Eye(SpellAction action, SpellArea area) => new(action, SpellComponentType.EyeCandy, area, 0, 0, null);
        SessionEffectDefinition? Effect(int number) => number == 62 ? new(62, [new EffectChange(EffectAttributeKind.Stat, 11, EffectChangeOperator.Add, -5)]) : null;
        var runs = SessionSpellRecords.Translate(Record(number: 150, components: [Damage(SpellAction.Begin, 0, 1, 1, 0), Eye(SpellAction.Begin, area)]));
        Assert.AreEqual(("RUNS", "", ""), Classify(runs, Effect, _ => null));
        var part = SessionSpellRecords.Translate(Record(number: 151, components: [Damage(SpellAction.Begin, 0, 1, 1, 0), new(SpellAction.Begin, SpellComponentType.Dispel, area, 0, 0, null)]));
        Assert.AreEqual(("PART", "Dispel", "Dispel"), Classify(part, Effect, _ => null));
        var inert = SessionSpellRecords.Translate(Record(number: 152, components: [Eye(SpellAction.Begin, area), new(SpellAction.End, SpellComponentType.Dispel, area, 0, 0, null)]));
        Assert.AreEqual(("INERT", "Dispel", "Dispel"), Classify(inert, Effect, _ => null));
        // A Destroy is left out; a Summon of a scenery prototype is ready, of a critter or an unread prototype is not, and a list pick (Proto 0) is not.
        var summon = (int proto) => SessionSpellRecords.Translate(Record(number: 153, components: [new(SpellAction.Begin, SpellComponentType.Summon, area, 0, 0, new SummonData(proto, 0, 0, 0)), new(SpellAction.End, SpellComponentType.Destroy, area, 0, 0, null)]));
        Assert.AreEqual(("RUNS", "", ""), Classify(summon(4050), Effect, file => file == 4070 ? SessionSpellCaster.SceneryObjectType : null), "a scenery summon and a destroy");
        Assert.AreEqual(("PART", "Summon", "Summon"), Classify(summon(4050), Effect, file => file == 4070 ? 14 : null), "a summon of an item is not ready; the destroy is taken");
        Assert.AreEqual(("PART", "Summon", "Summon"), Classify(summon(0), Effect, _ => SessionSpellCaster.SceneryObjectType), "a list pick is not ready; the destroy is taken");
    }

    /// <summary>The census of the record on both targets and the state word from it.</summary>
    private static (string State, string Hero, string Npc) Classify(SessionSpellRecord record, Func<int, SessionEffectDefinition?> effects, Func<int, int?> prototypeType)
    {
        var summon = record.Components.Any(c => c.Summon is { } data && !(data.Prototype > 0 && prototypeType(data.Prototype + SessionSpellCaster.PrototypeFileOffset) == SessionSpellCaster.SceneryObjectType));
        string Lists(string target) => string.Join(",", NotReady(record, target, effects).Split(',', StringSplitOptions.RemoveEmptyEntries)
            .Where(t => t != nameof(SpellComponentType.Destroy)).Concat(summon ? [nameof(SpellComponentType.Summon)] : []).Distinct().Order(StringComparer.Ordinal));
        var hero = Lists(Hero);
        var npc = Lists(Npc);
        if (hero == "" && npc == "") return ("RUNS", "", "");
        if (hero == "") return ("HERO", hero, npc);
        // A component the host logs as not ready names its type; the record is partly running when a component of another type, other than eye candy, is among its components.
        var notReady = hero.Split(',').ToHashSet();
        var takes = record.Components.Any(c => c.Type != SpellComponentType.EyeCandy && !notReady.Contains(c.Type.ToString()));
        return (takes ? "PART" : "INERT", hero, npc);
    }

    private static string Tally(IEnumerable<KeyValuePair<int, string>> states) =>
        string.Join(" ", new[] { "RUNS", "HERO", "PART", "INERT" }.Select(w => $"{w} {states.Count(s => s.Value == w)}"));
}
