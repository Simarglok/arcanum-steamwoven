/// <summary>
/// ARC-DEV-363 (slice T-b of the technology audit ARC-RES-104, docs/research/technology-audit-res-104.md sections 5 to 7): the technology census. Every technology record 140..222
/// (83 records) of the installed original (opt-in, <c>DAT_ROOT</c> = the game folder) has each component of every action applied by the cast host to the hero and to an NPC in turn,
/// by the harness of <see cref="SpellCensusRealDataTests"/> (a fresh session each; the host's component dispatch, not a cast). From the components the host logs as not ready each
/// record gets a <b>state</b>, the one word of the audit's component table (section 5), and the test fails when a record's state or its not-ready lists differ from <see cref="Expected"/>:
/// <list type="bullet">
/// <item><b>RUNS</b>: the host takes every component on both targets.</item>
/// <item><b>HERO</b>: every component is taken on the hero, but some are not on the NPC.</item>
/// <item><b>PART</b>: some component is not taken on the hero, but another component that is not eye candy is.</item>
/// <item><b>INERT</b>: nothing but the eye-candy line of the record is taken on the hero.</item>
/// </list>
/// Two components are not read off a creature target, which says nothing about them: a <b>Destroy</b> acts on a created object or a lying item (taken by <c>SessionSpellDestroyTests</c>,
/// <c>SessionSpellSummonTests</c> and the smoke stages <c>grenade</c>, <c>summon-flash</c>, <c>summon-wall</c>) and a <b>Summon</b> on an object entry summons nothing (TA9), so the host takes it there
/// whatever it summons. The census leaves Destroy out and reads Summon from the record and the installed prototype: it is ready when the record names a basic prototype whose file (+20) is a
/// scenery, as <c>SessionSpellCaster.SummonComponent</c> asks, and not ready for a list pick or a critter (E1-e).
/// It is the living status table of the audit: a slice that makes a component ready edits <see cref="Expected"/> in its own pull request, and the row's state flips with it. The records
/// carried by an item prototype (the 65 of the audit) are read from the same installation and counted by state. Numbers only; no game text is read or printed.
/// </summary>
[TestClass]
public sealed class TechCensusRealDataTests
{
    /// <summary>One row per technology record whose state is not RUNS: (record, state, the hero's not-ready types, the NPC's), each a sorted comma list. A record not listed is RUNS.
    /// Generated by the census on <c>origin/main</c> after ARC-DEV-362 (2026-11-11). Destroy and Summon are read as the class summary says.</summary>
