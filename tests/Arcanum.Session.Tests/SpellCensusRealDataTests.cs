    /// <summary>The census harness on a synthetic record (root checks): a ready Damage, a Movement no slice builds, and an Effect the host takes on the hero and on an NPC.</summary>
    [TestMethod]
    public void The_census_lists_the_components_the_host_logs_as_not_ready_per_target()
    {
        var area = new SpellArea(0x40, 0, 0, 0, -1);
        var record = SessionSpellRecords.Translate(Record(number: 90, components:
        [
            Damage(SpellAction.Begin, 0, 1, 1, 0),
            new(SpellAction.Begin, SpellComponentType.Movement, area, 0, 0, null),
            new(SpellAction.End, SpellComponentType.Effect, area, 0, 0, new EffectData(62, true, 1, (int)EffectCause.Spell, 0)),
        ]));
        SessionEffectDefinition? Effect(int number) => number == 62 ? new(62, [new EffectChange(EffectAttributeKind.Stat, 11, EffectChangeOperator.Add, -5)]) : null;
        Assert.AreEqual("Movement", NotReady(record, Hero, Effect));
        Assert.AreEqual("Movement", NotReady(record, Npc, Effect), "an NPC has an effect list too since ARC-DEV-348 (ARC-MAGIC-027 wired the component to it)");
        Assert.AreEqual("Effect,Movement", NotReady(record, Hero, _ => null), "without the effect tables an adding Effect is not ready on the hero either");
    }

    internal const string AreaEffectsPath = "rules/effect.mes";

    // Each component of the record, in file order, applied by a fresh host to the target as the run's action would (the hero the source and parent, no margin); the types the host
    // logged as not ready, sorted and distinct, and a session refusal of a taken component's write (ObjectFlagNotSaved, EffectNotSaved) by its event name, so it shows as a change too.
    internal static string NotReady(SessionSpellRecord record, string target, Func<int, SessionEffectDefinition?> effects)
    {
        using var owner = HeroStateTests.CreateWith(HeroStateTests.HalfElf());
        var fields = AttackStateTests.Npc(stats: AttackStateTests.Stats(), critterFlags: 0);
        var caster = new SessionSpellCaster(owner, n => n == record.Data.Number ? record : null,
            new Map(owner, new(SessionCritterCombat.From(Npc, fields).Combat!, 0, 0, 0, 0, 0)), new Events()) { EffectDefinitions = effects, Social = new CensusSocial(), Teleport = new CensusTeleport(), UseObject = CensusUse.Run };
        var hero = caster.RunObject(Hero)!;
        var to = caster.RunObject(target)!;
        var tile = target == Hero ? HeroTile : NpcTile;
        foreach (var c in record.Components)
            caster.Apply(new SpellRun(0, record.Data.Number, c.Action, hero, hero, HeroTile, to, tile, null, SpellRunFlags.Active), c.Index, new(to, tile));
        return string.Join(",", caster.Log.Where(e => e.Kind is SpellCastEventKind.ComponentNotReady or SpellCastEventKind.ObjectFlagNotSaved or SpellCastEventKind.EffectNotSaved)
            .Select(e => e.Kind == SpellCastEventKind.ComponentNotReady ? ((SpellComponentType)e.Value).ToString() : e.Kind.ToString()).Distinct().Order(StringComparer.Ordinal));
    }
