    [TestMethod, TestCategory("RealData")]
    public void Every_record_leaves_exactly_the_listed_components_not_ready()
    {
        var root = Environment.GetEnvironmentVariable("DAT_ROOT");
        if (string.IsNullOrWhiteSpace(root)) Assert.Inconclusive("DAT_ROOT is required for the opt-in spell census; this is not a synthetic pass.");
        using var stack = ContentStack.Open(ContentMountPlan.Discover(root).Plan!).Stack!;
        var spells = SpellData.Open(stack, SpellRecordMode.LikeOriginal);
        Assert.AreEqual(SpellDataStatus.Read, spells.Status, $"{spells.Refusal}");
        var source = ContentPhase.Candidate(stack, AreaEffectsPath, ContentLoadPhase.GameStart) ?? throw new AssertFailedException($"{AreaEffectsPath} missing");
        var read = stack.Read(source);
        Assert.AreEqual(ContentReadStatus.Read, read.Status);
        var effects = MesFile.Parse(read.Bytes!, new()).File ?? throw new AssertFailedException($"{AreaEffectsPath} not parsed");
        // The viewer's rule of a number (TerrainViewerSpellCast: SessionEffectDefinition.FromRule over the effect tables, a rule the session refuses is none). Numbers 0..49 come from
        // the module's gameeffect.mes there; the records 0..139 name none of them (asserted below), so effect.mes alone answers here.
        SessionEffectDefinition? Effect(int number)
        {
            try { return EffectRules.Read(effects, number).Rule is { } rule ? SessionEffectDefinition.FromRule(rule) : null; }
            catch (ArgumentException) { return null; }
        }

        var expected = Expected.ToDictionary(e => e.Record, e => (e.Hero, e.Npc));
        Assert.AreEqual(Expected.Length, expected.Count, "one row per record");
        var differences = new List<string>();
        var ready = 0;
        for (var number = 0; number < SpellRecord.FirstTechnology; number++)
        {
            var record = SessionSpellRecords.Translate(spells.Data!.Records[number]);
            Assert.IsFalse(record.Components.Any(c => c.Effect is { Effect: < EffectRules.FirstNumber }), $"record {number} names a module effect (0..49)");
            var actual = (Hero: NotReady(record, Hero, Effect), Npc: NotReady(record, Npc, Effect));
            if (number < SpellRecord.CollegeSpells && actual is ("", "")) ready++;
            if (actual != expected.GetValueOrDefault(number, ("", ""))) differences.Add($"        ({number}, \"{actual.Hero}\", \"{actual.Npc}\"),");
        }
        Console.WriteLine($"college spells whose every component the host takes on both targets: {ready} of {SpellRecord.CollegeSpells}");
        Assert.AreEqual(0, differences.Count, "the census changed; the rows as they are now (a row of two empty lists is removed):\n" + string.Join("\n", differences));
    }

    /// <summary>ARC-AI-2125 (ledger GW10, UO2 and UO5): goal 43 starts only from an AGoal component (GT59) and tests no object type itself, so what can be pushed is what the component's area admits. Every installed
    /// spell and technology record with such a component targets, with the object test running (a self, target or radius bit, low 0x15), with the critter bit (0x40) or with the item-weight-below-5 bit (0x4000000, no critter bit): a portal, container or scenery is never pushed, so the
    /// pusher-as-actor guard-witness call of a pushed non-critter (GW10) never happens in the original with the installed data. Numbers only.</summary>
    [TestMethod, TestCategory("RealData")]
    public void Every_knockback_component_targets_a_critter_or_a_light_item()
    {
        var root = Environment.GetEnvironmentVariable("DAT_ROOT");
        if (string.IsNullOrWhiteSpace(root)) Assert.Inconclusive("DAT_ROOT is required for the opt-in knockback target check; this is not a synthetic pass.");
        using var stack = ContentStack.Open(ContentMountPlan.Discover(root).Plan!).Stack!;
        var spells = SpellData.Open(stack, SpellRecordMode.LikeOriginal);
        Assert.AreEqual(SpellDataStatus.Read, spells.Status, $"{spells.Refusal}");
        var records = new SortedSet<int>();
        for (var number = 0; number < SpellRecord.Count; number++)
        {
            foreach (var component in SessionSpellRecords.Translate(spells.Data!.Records[number]).Components.Where(c => c.AnimationGoal == SessionSpellCaster.KnockbackGoal))
            {
                records.Add(number);
                var low = (uint)component.Area.Targets;
                var critter = (low & 0x40) != 0;
                var lightItem = (low & 0x4000000) != 0;
                // The object test (0x4F2D20) runs only with a self, target or radius bit (low 0x15); without one the tile test passes any object.
                Assert.IsTrue((low & 0x15) != 0, $"record {number}: a knockback component whose area (0x{component.Area.Targets:X}) skips the object test");
                Assert.IsTrue(critter || lightItem, $"record {number}: a knockback component whose area (0x{component.Area.Targets:X}) admits other objects than critters and items of weight below 5");
            }
        }
        CollectionAssert.AreEqual(new[] { 2, 12, 131, 132, 175, 176, 185, 201, 208, 219, 220 }, records.ToArray(), "the records with a knockback component changed; check their areas and update ledger GW10 and UO5");
    }

